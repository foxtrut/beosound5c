# ── Lookup ──

def normalise(lang) -> str:
    """config.json's "language" → a key STRINGS has. "auto" means English:
    a service has no browser locale to follow the way the web views do."""
    key = str(lang or "auto").lower().split("-")[0]
    return key if key in STRINGS else "en"


def t(key: str, lang) -> str:
    """A UI label the radio source invents itself."""
    strings = STRINGS[normalise(lang)]
    return strings.get(key) or STRINGS["en"].get(key, key)


def country(name: str, lang) -> str:
    """The API's English country name, in `lang`. Unknown names pass through
    unchanged — the name doubles as the browse path, so it always exists."""
    if normalise(lang) == "da":
        return COUNTRIES_DA.get((name or "").strip().lower(), name)
    return name


def language(name: str, lang) -> str:
    """A language name from the API. Falls back to title case, as before."""
    raw = (name or "").strip()
    if normalise(lang) == "da":
        return LANGUAGES_DA.get(raw.lower(), raw.title())
    return raw.title()


def genre_label(name: str, lang) -> str:
    """A genre as a browse heading or list entry. Falls back to title case,
    which is what the genre list has always shown in English."""
    raw = (name or "").strip()
    if normalise(lang) == "da":
        return GENRES_DA.get(raw.lower(), raw.title())
    return raw.title()


def genre_tag(name: str, lang) -> str:
    """A genre inside a station subtitle or the PLAYING view, where the tag
    has always been shown exactly as the station submitted it — usually
    lower case. English keeps that; Danish title-cases what it can't
    translate, so a subtitle doesn't read "Nyheder, pop"."""
    raw = (name or "").strip()
    if normalise(lang) == "da":
        return GENRES_DA.get(raw.lower(), raw.title())
    return raw
